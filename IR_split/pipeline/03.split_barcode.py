"""Split IR paired FASTQ files by sample primer barcode.

IR read layout:
    R1: [10 bp UMI][8 bp sample primer barcode][insert]
    R2: [insert]

The sample/barcode mapping is read exclusively from the CSV generated by
``match_sample_barcode.py``. In ``raw`` mode matching R1 reads are written
after removing the UMI and primer barcode, with ``#<UMI>`` added to both paired
headers. In ``presplit`` mode the existing tagged FASTQ is validated and
adopted without a second barcode trim. Both modes publish the same compressed
read-to-UMI sidecar before clean-header removes the tag. Plain and gzip FASTQ
are accepted. Outputs preserve ``<Lane>/<pair_stem>/<sample_id>/`` hierarchy.
"""

